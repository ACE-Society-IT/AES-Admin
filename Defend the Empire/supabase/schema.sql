CREATE INDEX IF NOT EXISTS idx_dte_crisis_wave_order ON public.dte_crisis(wave_order);
CREATE INDEX IF NOT EXISTS idx_dte_leaderboard_valuation ON public.dte_leaderboard(current_valuation DESC);
