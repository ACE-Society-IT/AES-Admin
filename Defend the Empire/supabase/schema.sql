ALTER TABLE public.dte_teams ADD COLUMN IF NOT EXISTS current_valuation bigint NOT NULL DEFAULT 100000;
ALTER TABLE public.dte_teams ADD COLUMN IF NOT EXISTS last_answered_wave integer NOT NULL DEFAULT -1;

CREATE TABLE IF NOT EXISTS public.dte_leaderboard (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id text NOT NULL UNIQUE REFERENCES public.dte_teams(id) ON DELETE CASCADE,
  team_name text NOT NULL,
  rank integer NOT NULL DEFAULT 1,
  starting_valuation bigint NOT NULL DEFAULT 100000,
  current_valuation bigint NOT NULL DEFAULT 100000,
  net_delta bigint NOT NULL DEFAULT 0,
  crises_resolved integer NOT NULL DEFAULT 0,
  last_option_locked text,
  last_answered_wave integer NOT NULL DEFAULT -1,
  manual_adjustment bigint NOT NULL DEFAULT 0,
  playstyle text NOT NULL DEFAULT 'Balanced Hedger',
  decisions jsonb NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now()
);

