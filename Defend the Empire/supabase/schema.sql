-- ============================================================================
-- DEFEND THE EMPIRE (DTE) — SUPABASE SCHEMA FOR PROJECT: INVESTOMANIA
-- Tables: dte_crisis, dte_teams, dte_leaderboard
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.dte_crisis (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wave_order integer NOT NULL DEFAULT 1,
  icon text NOT NULL DEFAULT '⚡',
  division text NOT NULL DEFAULT 'Operations',
  title text NOT NULL,
  story text NOT NULL,
  options jsonb NOT NULL DEFAULT '[]'::jsonb,
  status text NOT NULL DEFAULT 'idle' CHECK (status IN ('idle', 'running', 'paused', 'completed')),
  selection_open boolean NOT NULL DEFAULT false,
  duration_seconds integer NOT NULL DEFAULT 360,
  remaining_seconds integer NOT NULL DEFAULT 360,
  started_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.dte_teams (
  id text PRIMARY KEY,
  team_name text NOT NULL UNIQUE,
  passcode text NOT NULL DEFAULT '1234',
  playstyle text NOT NULL DEFAULT 'Balanced Hedger',
  starting_valuation bigint NOT NULL DEFAULT 100000,
  decisions jsonb NOT NULL DEFAULT '{}'::jsonb,
  manual_adjustment bigint NOT NULL DEFAULT 0,
  adjustment_log jsonb NOT NULL DEFAULT '[]'::jsonb,
  current_valuation bigint NOT NULL DEFAULT 100000,
  last_answered_wave integer NOT NULL DEFAULT -1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

